# -*- coding: utf-8 -*-
"""質問投稿の記入ルールの正本。

画面の案内文と、入力欄のプレースホルダは、両方ともここから生成する。
同じ内容を2か所にベタ書きすると、片方だけ直して食い違う。

■影響 を足した経緯（2026-09-15）
    質問 #1265 / #1266。実際には対応不要なメールが「本来当方で対応すべきメール」
    と書かれ、業務が止まっている前提で原因究明を進めた。フィルタ86本の全件照合、
    ツールの権限確認、メールヘッダ解析、操作履歴の復元まで行って、最後に
    「個別の確認はしておらず、そのままアーカイブしている」と判明した。
    「困っていないが気になる」を書く欄が無いと、報告するために事実が盛られる。
    影響は、調べるかどうかではなく、どこまで調べるかを決める情報。
"""

# 回答者は作業の中身を持っていない、という前提。
# 作業を渡すとは、その作業の状態を持つ責任ごと渡すこと。
# 「ご存じの前提」で書かれると、回答側は状態を取り戻すところから始めることになる。
PREMISE = [
    "この質問に答えるのは、作業をお渡ししている側です。",
    "日々の手順・現在の設定・現行ルールの内容は、インハナさん側にしかありません。",
    "「ご存じの前提」で書かれますと、回答できません。",
]

# 質問本文の見出しと、その欄に何を書くか。
SECTIONS = [
    ("■事象", "何が、どこで起きているか"),
    ("■発生日時・対象", "いつ／何件／どのメール・注文・商品か"),
    ("■試したこと", "実施した操作と、その結果"),
    ("■こちらで確認済み", "自分で調べた範囲とその結果。「該当なし」も記載してください"),
    ("■影響", "この事象で、実際に何が止まっていますか。"
              "止まっていない場合は「業務は止まっていない」と記載してください"),
    ("■確認したいこと", "判断してほしいこと／確認が取れなかった場合の次の動き"),
]

# 空欄・否定をそのまま書ける欄。ここが無いと、報告するために事実が盛られる。
# 消すと test_qa_posting_rules が落ちる。
REQUIRED_HEADINGS = ("■こちらで確認済み", "■影響")

# タイトルの例。案内文と入力欄の両方がここを見る（2か所に書かない）。
TITLE_EXAMPLE = "CS・保険証券の発行タイミングについて"
TITLE_PLACEHOLDER = "例：" + TITLE_EXAMPLE

RULES = [
    "タイトルは「大カテゴリ＋中カテゴリ」の粒度で（例：{}）".format(TITLE_EXAMPLE),
    "下の項目を、それぞれ「■」で区切って記載すること",
    "画像だけで説明を省かず、文章だけで内容が伝わるように記載すること",
    "「該当なし」「業務は止まっていない」も、そのまま書くこと。判断に必要な情報です",
]


def rules_markdown() -> str:
    """画面上部の案内文（st.info 用）。"""
    lines = ["**前提**"]
    lines += [p + "  " for p in PREMISE]          # 行末2スペース＝markdownの改行
    lines += ["", "**記入ルール**"]
    lines += ["- " + r for r in RULES]
    lines += ["", "**記載する項目**"]
    lines += ["- {}　{}".format(head, desc) for head, desc in SECTIONS]
    return "\n".join(lines)


def body_placeholder() -> str:
    """質問本文の入力欄に薄く出る見本。"""
    return "\n".join("{}\n　{}\n".format(head, desc) for head, desc in SECTIONS)
